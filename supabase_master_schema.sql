-- --------------------------------------------------------------------
-- 8. TABLE: audit_logs (Log Aktivitas Audit Sistem)
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.audit_logs (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    waktu VARCHAR(100) NOT NULL,
