-- --------------------------------------------------------------------
-- 7. TABLE: jurnal_umum (Jurnal Transaksi Keuangan)
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.jurnal_umum (
    id VARCHAR(100) PRIMARY KEY,
    tanggal DATE NOT NULL,
    no_bukti VARCHAR(100) NOT NULL,
    keterangan TEXT NOT NULL,
    kode_akun VARCHAR(50) REFERENCES public.chart_of_accounts(kode) ON DELETE CASCADE,
